<?php

declare(strict_types=1);

namespace App\Models;

use App\Concerns\RecordsActivity;
use App\Enums\CollectionFrequency;
use App\Enums\DenominatorBasis;
use App\Enums\IndicatorCollector;
use App\Enums\IndicatorMeasure;
use App\Enums\ResultType;
use App\Notifications\TracksActivity;
use Carbon\CarbonImmutable;
use Database\Factories\LibraryIndicatorFactory;
use Illuminate\Database\Eloquent\Attributes\Fillable;
use Illuminate\Database\Eloquent\Attributes\Scope;
use Illuminate\Database\Eloquent\Builder;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\HasMany;

/**
 * An entry of the central Indicator Library MEAL owns (contracts.md §11.1).
 *
 * Proposals and projects pick their indicators from here; each picked
 * indicator is an `indicators` row pointing back through
 * `library_indicator_id`. `code`, `serial` and `is_active` are never mass
 * assigned: the code is generated by App\Support\IndicatorCode and the flag
 * moves only through DeactivateLibraryIndicator / ReactivateLibraryIndicator.
 *
 * @property int $id
 * @property string $code
 * @property int|null $program_id
 * @property string $level_ref
 * @property int $serial
 * @property string $name_ar
 * @property string|null $name_en
 * @property string|null $definition
 * @property string|null $calculation_method
 * @property IndicatorMeasure $measure
 * @property string|null $unit
 * @property string|null $numerator_label
 * @property string|null $denominator_label
 * @property DenominatorBasis|null $denominator_basis
 * @property bool $is_disaggregated
 * @property IndicatorCollector $collected_by
 * @property bool $is_cumulative
 * @property CollectionFrequency $frequency
 * @property string|null $frequency_note
 * @property int|null $follow_up_months
 * @property ResultType|null $suggested_level
 * @property string|null $data_source
 * @property string|null $means_of_verification
 * @property bool $is_legacy
 * @property bool $is_active
 * @property CarbonImmutable|null $created_at
 * @property CarbonImmutable|null $updated_at
 */
#[Fillable([
    'program_id', 'level_ref', 'name_ar', 'name_en', 'definition', 'calculation_method', 'measure', 'unit',
    'numerator_label', 'denominator_label', 'denominator_basis', 'is_disaggregated', 'collected_by',
    'is_cumulative', 'frequency', 'frequency_note', 'follow_up_months', 'suggested_level', 'data_source',
    'means_of_verification', 'is_legacy',
])]
class LibraryIndicator extends Model implements TracksActivity
{
    /** @use HasFactory<LibraryIndicatorFactory> */
    use HasFactory, RecordsActivity;

    /**
     * Mirror the column defaults so an entry that has not been round-tripped
     * through the database still reports them under strict mode (the
     * factory leaves these columns to the database).
     *
     * @var array<string, mixed>
     */
    protected $attributes = [
        'measure' => 'numeric',
        'is_disaggregated' => false,
        'collected_by' => 'project_team',
        'is_cumulative' => false,
        'is_legacy' => false,
        'is_active' => true,
    ];

    /**
     * The indicators picked from this entry.
     *
     * @return HasMany<Indicator, $this>
     */
    public function indicators(): HasMany
    {
        return $this->hasMany(Indicator::class);
    }

    /**
     * Entries still offered for new selection. A deactivated entry stays on
     * the indicators that already use it.
     *
     * @param  Builder<self>  $query
     */
    #[Scope]
    protected function active(Builder $query): void
    {
        $query->where('is_active', true);
    }

    /**
     * The name in the current language; an entry with no English name shows
     * its Arabic name everywhere.
     */
    public function localizedName(): string
    {
        if (app()->getLocale() === 'ar' || blank($this->name_en)) {
            return $this->name_ar;
        }

        return $this->name_en;
    }

    public function activityModule(): string
    {
        return 'indicator-library';
    }

    public function activityLabel(): string
    {
        return (string) $this->activityAttribute('code');
    }

    public function activityProgramId(): ?int
    {
        $programId = $this->activityAttribute('program_id');

        return $programId === null ? null : (int) $programId;
    }

    /**
     * @return array<string, string>
     */
    public function activityEvents(): array
    {
        return [
            'is_active' => 'deactivated',
            'name_ar' => 'updated',
            'name_en' => 'updated',
            'code' => 'updated',
            'measure' => 'updated',
            'definition' => 'updated',
            'calculation_method' => 'updated',
            'unit' => 'updated',
            'denominator_basis' => 'updated',
            'is_disaggregated' => 'updated',
            'collected_by' => 'updated',
            'is_cumulative' => 'updated',
            'frequency' => 'updated',
            'follow_up_months' => 'updated',
        ];
    }

    /**
     * Turning an entry back on is its own event.
     */
    protected function activityEventForChange(string $field, mixed $old, mixed $new): ?string
    {
        if ($field === 'is_active') {
            return (bool) $new ? 'reactivated' : 'deactivated';
        }

        return $this->activityEvents()[$field] ?? null;
    }

    /**
     * Get the attributes that should be cast.
     *
     * @return array<string, string|class-string>
     */
    protected function casts(): array
    {
        return [
            'program_id' => 'integer',
            'serial' => 'integer',
            'measure' => IndicatorMeasure::class,
            'denominator_basis' => DenominatorBasis::class,
            'is_disaggregated' => 'boolean',
            'collected_by' => IndicatorCollector::class,
            'is_cumulative' => 'boolean',
            'frequency' => CollectionFrequency::class,
            'follow_up_months' => 'integer',
            'suggested_level' => ResultType::class,
            'is_legacy' => 'boolean',
            'is_active' => 'boolean',
        ];
    }
}
